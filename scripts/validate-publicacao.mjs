#!/usr/bin/env node
/**
 * Trinco de publicação.
 *
 * O Docusaurus publica TODO arquivo sob docs/, esteja ele em uma sidebar ou não.
 * Página fora da sidebar não fica oculta — fica sem link, acessível por URL e
 * indexável. É assim que um rascunho pessoal deixado em docs/ vira público sem
 * ninguém notar.
 *
 * Invariante: toda página é OU navegável (consta de uma sidebar) OU
 * deliberadamente `draft: true`. Nada publica por acidente.
 *
 * Uso: npm run validate:publicacao
 */

import {readFileSync, readdirSync, statSync} from 'node:fs';
import {join, dirname, resolve, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const raiz = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dirDocs = join(raiz, 'docs');
const sidebars = readFileSync(join(raiz, 'sidebars.ts'), 'utf8');

const erros = [];
const avisos = [];

// Pastas cobertas por {type:'autogenerated', dirName:'...'}
const autogeradas = [...sidebars.matchAll(/dirName:\s*'([^']+)'/g)].map((m) => m[1]);

function listar(dir) {
  const saida = [];
  for (const nome of readdirSync(dir)) {
    const caminho = join(dir, nome);
    if (statSync(caminho).isDirectory()) {
      saida.push(...listar(caminho));
    } else if (/\.mdx?$/.test(nome)) {
      saida.push(caminho);
    }
  }
  return saida;
}

const arquivos = listar(dirDocs);

for (const arquivo of arquivos) {
  const rel = relative(dirDocs, arquivo).replace(/\\/g, '/');
  const id = rel.replace(/\.mdx?$/, '');
  const texto = readFileSync(arquivo, 'utf8');

  // front matter
  const fm = texto.startsWith('---') ? texto.slice(3, texto.indexOf('\n---', 3)) : '';
  const ehDraft = /^\s*draft\s*:\s*true\s*$/m.test(fm);
  const ehUnlisted = /^\s*unlisted\s*:\s*true\s*$/m.test(fm);
  const temSlugRaiz = /^\s*slug\s*:\s*\/\s*$/m.test(fm);

  // navegável?
  const citadaNaSidebar = sidebars.includes(`'${id}'`);
  const emPastaAutogerada = autogeradas.some((d) => id.startsWith(`${d}/`));
  const navegavel = citadaNaSidebar || emPastaAutogerada || temSlugRaiz;

  if (!navegavel && !ehDraft && !ehUnlisted) {
    erros.push(
      `docs/${rel}\n` +
        `      publica em /${id} mas não consta de nenhuma sidebar.\n` +
        `      Escolha: registre em sidebars.ts, ou marque 'draft: true' se for confidencial.`,
    );
  }

  // Draft registrada em sidebar não é erro: o Docusaurus a remove da navegação
  // em silêncio. Vale registrar, porque explica item que "desapareceu" do menu.
  if (ehDraft && citadaNaSidebar) {
    avisos.push(`docs/${rel} está em sidebars.ts, mas é draft — sai da navegação em produção`);
  }
}

const total = arquivos.length;
const drafts = arquivos.filter((a) => {
  const t = readFileSync(a, 'utf8');
  const fm = t.startsWith('---') ? t.slice(3, t.indexOf('\n---', 3)) : '';
  return /^\s*draft\s*:\s*true\s*$/m.test(fm);
});

console.log('Trinco de publicação');
console.log(`  páginas em docs/        : ${total}`);
console.log(`  não publicadas (draft)  : ${drafts.length}`);
for (const d of drafts) {
  console.log(`      · ${relative(dirDocs, d).replace(/\\/g, '/')}`);
}
console.log(`  publicadas              : ${total - drafts.length}`);

if (avisos.length) {
  console.log('');
  for (const a of avisos) console.log(`  aviso: ${a}`);
}

if (erros.length) {
  console.error(`\n${erros.length} página(s) publicando sem constar de sidebar:`);
  for (const e of erros) console.error(`  ✗ ${e}`);
  process.exit(1);
}

console.log('\n✓ nada publica por acidente');
